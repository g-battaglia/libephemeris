#!/usr/bin/env python3
"""Generate the compact canonical VCW locator and Gauss-Legendre Rust tables.

Run from the repository with an existing mpmath installation:
    python tools/generators/gen_gmst_canonical_table.py

Published decimal series are evaluated at 90 digits, GL32 and five-century
panels by default. Only final rows are converted to binary64. This is a
deterministic ordinary quadrature table; convergence is checked independently
by the reference tests and is not a physical-accuracy assertion.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tools.generators.gmst_origin_reference import MeanOriginReference, require


def rust_float(value):
    """A round-tripping Rust binary64 literal, including an explicit decimal."""
    text = repr(float(value))
    require(text not in ("inf", "-inf", "nan"), "nonfinite generated value")
    return text if "." in text or "e" in text else text+".0"


def render_table(reference, *, start=-2000, step=10, count=401):
    """Render s nodes and both GL rules; custom grids support small tests only."""
    require(type(start) is int and type(step) is int and type(count) is int,
            "table grid must contain integers")
    require(step > 0 and count > 0 and -2000 <= start <= start+step*(count-1) <= 2000,
            "invalid table grid")
    lines = [
        "// Generated by tools/generators/gen_gmst_canonical_table.py; do not edit.",
        f"// Published VCW decimals; {reference.dps} digits, GL{reference.order}, "
        f"panel width {reference.mp.nstr(reference.panel_width)} Julian centuries.",
        "// CIO_S(T) = integral_0^T -(X*Y' - Y*X')/(1+Z) dT, radians; s(0)=0.",
        "// Gauss-Legendre nodes/weights are on [-1,1]. Final rounding is binary64.",
        "", f"pub(super) const NODE_START_CENTURIES: f64 = {rust_float(start)};",
        f"pub(super) const NODE_STEP_CENTURIES: f64 = {rust_float(step)};",
        f"pub(super) const CIO_S: [f64; {count}] = [",
    ]
    entries = [(start+step*index, rust_float(reference.locator_centuries(start+step*index)))
               for index in range(count)]
    width = max(len(literal)+1 for _, literal in entries)
    for t, literal in entries:
        lines.append(f"    {literal+',':<{width}} // T={t}")
    lines += [
        "];", "",
    ]
    for order in (16, 32):
        nodes, weights = reference.mp.gauss_quadrature(order, "legendre")
        if order == 32:
            lines.append("#[cfg(test)]")
        lines.append(f"pub(super) const GAUSS{order}: [(f64, f64); {order}] = [")
        lines.extend(f"    ({rust_float(x)}, {rust_float(w)})," for x, w in zip(nodes, weights))
        lines += ["];", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT/"core/src/time/canonical_sidereal_table.rs")
    parser.add_argument("--dps", type=int, default=90)
    parser.add_argument("--order", type=int, choices=(16, 32), default=32)
    parser.add_argument("--panel-width", type=int, default=5)
    parser.add_argument("--check", action="store_true", help="compare without modifying output")
    args = parser.parse_args(argv)
    reference = MeanOriginReference(args.dps, args.order, args.panel_width)
    text = render_table(reference)
    if args.check:
        require(args.output.is_file() and args.output.read_text() == text,
                "canonical sidereal table is not current")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    print(f"canonical table: 401 locator nodes, GL16/32; {len(text.splitlines())} lines; {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
