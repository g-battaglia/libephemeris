        std::fs::write(&path, b"keep").expect("scratch file");
        let (code, stdout, _) = wizard_io("no\n", &path, false);
        assert_eq!(code, EXIT_OK);
        assert!(stdout.contains("Aborted."));
        assert_eq!(std::fs::read_to_string(&path).expect("kept"), "keep");
