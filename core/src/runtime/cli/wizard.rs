/// Required, optional or fallback role in the setup file report.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum FileNeed {
    Required,
    Optional,
    Fallback,
}

/// One file row of the post-wizard status report.
struct WizardFile {
    filename: String,
    size_mb: f64,
    category: &'static str,
    need: FileNeed,
    subdir: &'static str,
}

/// List files for the selected tier and calculation mode without I/O.
///
/// `auto` and `leb` list a required LEB2 core and optional companions.
/// `auto` lists the DE kernel as a fallback; `skyfield` requires it.
/// Planet centers are a fallback in `auto`, optional in `horizons`, and
/// required in other modes.
fn wizard_required_files(tier: &str, mode: &str) -> Vec<WizardFile> {
    let mut files = Vec::new();
    if mode == "auto" || mode == "leb" {
        for group in leb::LEB2_GROUPS {
            files.push(WizardFile {
                filename: format!("{tier}_{group}.leb2"),
                size_mb: wizard_leb2_group_size(tier, group),
                category: "LEB2",
                need: if group == "core" {
                    FileNeed::Required
                } else {
                    FileNeed::Optional
                },
                subdir: "leb",
            });
        }
    }
    if mode == "auto" || mode == "skyfield" {
        let (name, size) = wizard_de_kernel(tier);
        files.push(WizardFile {
            filename: name.to_string(),
            size_mb: size,
            category: "DE kernel",
            need: if mode == "auto" {
                FileNeed::Fallback
            } else {
                FileNeed::Required
            },
            subdir: "",
        });
    }
    files.push(WizardFile {
        filename: format!("planet_centers_{tier}.bsp"),
        size_mb: wizard_planet_centers_size(tier),
        category: "Planet centers",
        need: if mode == "auto" {
            FileNeed::Fallback
        } else if mode == "horizons" {
            FileNeed::Optional
        } else {
            FileNeed::Required
        },
        subdir: "",
    });
    files
}

/// Format MB as a whole number below 1024 MB, otherwise as GB with one decimal.
fn format_size_mb(size_mb: f64) -> String {
    if size_mb >= 1024.0 {
        format!("{:.1} GB", size_mb / 1024.0)
    } else {
        format!("{:.0} MB", size_mb)
    }
}

/// Expand a leading `~/` using the HOME override or native user profile.
///
/// Return all other paths unchanged; no filesystem access is performed.
fn expand_tilde(path: &str) -> PathBuf {
    if let Some(rest) = path.strip_prefix("~/") {
        if let Some(home) = crate::platform::user_home_directory() {
            return home.join(rest);
        }
    }
    PathBuf::from(path)
}

/// Report file presence, download commands and next steps after setup.
///
/// Check paths read-only under the selected data directory. Presence does not
/// validate file contents. This report does not download or modify data files.
fn run_wizard_post(
    out: &mut dyn std::io::Write,
    config: &WizardConfig,
    data_dir: &str,
    output: &str,
) {
    let root = expand_tilde(data_dir);
    let files = wizard_required_files(&config.precision, &config.mode);
    writeln!(out, "\n  Files needed for your configuration:\n").ok();
    let mut missing_required = 0u32;
    let mut missing_required_size = 0.0;
    let mut missing_fallback = 0u32;
    let mut missing_fallback_size = 0.0;
    for file in &files {
        let path = if file.subdir.is_empty() {
            root.join(&file.filename)
        } else {
            root.join(file.subdir).join(&file.filename)
        };
        let suffix = match file.need {
            FileNeed::Required => "",
            FileNeed::Optional => " (optional)",
            FileNeed::Fallback => " (fallback)",
        };
        if path.exists() {
            writeln!(
                out,
                "    [OK] {:<30} {:>8}  {}{suffix}",
                file.filename,
                format_size_mb(file.size_mb),
                file.category
            )
            .ok();
        } else {
            writeln!(
                out,
                "    [--] {:<30} {:>8}  {}{suffix}",
                file.filename,
                format_size_mb(file.size_mb),
                file.category
            )
            .ok();
            match file.need {
                FileNeed::Required => {
                    missing_required += 1;
                    missing_required_size += file.size_mb;
                }
                FileNeed::Fallback => {
                    missing_fallback += 1;
                    missing_fallback_size += file.size_mb;
                }
                FileNeed::Optional => {}
            }
        }
    }
    writeln!(out).ok();
    if missing_required == 0 && missing_fallback == 0 {
        writeln!(out, "  All files for this mode are present!").ok();
    } else {
        if missing_required > 0 {
            writeln!(
                out,
                "  Missing required: {missing_required} file(s) (~{})",
                format_size_mb(missing_required_size)
            )
            .ok();
        }
        if missing_fallback > 0 {
            writeln!(
                out,
                "  Missing fallback: {missing_fallback} file(s) (~{})",
                format_size_mb(missing_fallback_size)
            )
            .ok();
        }
        writeln!(out, "\n  To download, run:").ok();
        if config.mode == "auto" || config.mode == "leb" {
            writeln!(out, "    libephemeris download leb2-{}", config.precision).ok();
        }
        if config.mode == "auto" || config.mode == "skyfield" {
            writeln!(out, "    libephemeris download {}", config.precision).ok();
        }
    }
    writeln!(out, "\n  Next steps:").ok();
    writeln!(out, "  - Commit {output} to version control").ok();
    writeln!(out, "  - Run 'libephemeris status' to verify your setup").ok();
    writeln!(
        out,
        "  - Run 'libephemeris download leb2-{}' to fetch missing files later",
        config.precision
    )
    .ok();
    writeln!(out).ok();
}

/// Run interactive `init` over the supplied input, output and error streams.
///
/// Ask numbered setup questions, write the selected configuration, then report
/// local file presence. No data is downloaded; missing directories are not created.
/// Return 0 after a successful write or declined overwrite. EOF, exhausted
/// prompt retries and configuration write failures return 1 with a diagnostic.
/// Prompt I/O failures abort; final report write failures are ignored.
fn run_wizard_io(
    input: &mut dyn std::io::BufRead,
    out: &mut dyn std::io::Write,
    err: &mut dyn std::io::Write,
    output: &str,
    force: bool,
) -> i32 {
    if Path::new(output).exists() && !force {
        // Mirrors the release guard: declining keeps the file and exits
        // normally, while a closed stdin aborts like a prompt interrupt.
        match ask_yes_no(
            input,
            out,
            &format!("{output} already exists. Overwrite?"),
            false,
        ) {
            Some(true) => {}
            Some(false) => {
                writeln!(out, "Aborted.").ok();
                return EXIT_OK;
            }
            None => {
                writeln!(out, "Aborted.").ok();
                return EXIT_FAILED;
            }
        }
    }
    // Abort helper: EOF or exhausted retries close the run like the
    // release prompt abort (exit 1, nothing written).
    macro_rules! ask {
        ($expr:expr) => {
            match $expr {
                Some(answer) => answer,
                None => {
                    writeln!(out, "Aborted.").ok();
                    return EXIT_FAILED;
                }
            }
        };
    }

    writeln!(out, "\nlibephemeris configuration wizard").ok();
    writeln!(out, "\nQuick setup").ok();
    writeln!(
        out,
        "  Recommended: medium precision, auto mode, ~/.libephemeris"
    )
    .ok();
    writeln!(out, "  You can always edit the generated file later.").ok();
    let use_defaults = ask!(ask_yes_no(input, out, "Use defaults?", true));

    let (config, data_dir) = if use_defaults {
        writeln!(out).ok();
        (WizardConfig::defaults(), "~/.libephemeris".to_string())
    } else {
        writeln!(out, "\nPrecision tier").ok();
        let tier = ask!(ask_choice(
            input,
            out,
            &[
                ("base", "~31 MB 1849-2150 CE"),
                ("medium", "~114 MB 1549-2650 CE"),
                ("extended", "~3.0 GB -13200 to +17191 CE"),
            ],
            1,
        ));

        writeln!(out, "\nCalculation mode").ok();
        let mode = ask!(ask_choice(
            input,
            out,
            &[
                ("auto", "LEB -> Horizons -> Skyfield (recommended)"),
                ("leb", "Precomputed polynomials (~14x faster)"),
                ("skyfield", "DE kernel via Skyfield"),
                ("horizons", "NASA JPL API (requires internet)"),
            ],
            0,
        ));

        writeln!(out, "\nMinor bodies").ok();
        let auto_spk_default = mode == "auto" || mode == "skyfield";
        match mode.as_str() {
            "auto" | "leb" => {
                writeln!(
                    out,
                    "  LEB files cover the body groups present in your installed"
                )
                .ok();
                writeln!(
                    out,
                    "  tier companions. Enable auto-download for any *other* minor"
                )
                .ok();
                writeln!(out, "  body you request (e.g. Eros, Sedna)?").ok();
            }
            "skyfield" => {
                writeln!(
                    out,
                    "  The DE kernel only contains the major planets and the Moon."
                )
                .ok();
                writeln!(
                    out,
                    "  Enable auto-download of SPK kernels from JPL Horizons for"
                )
                .ok();
                writeln!(out, "  asteroids, centaurs, and TNOs when requested?").ok();
            }
            _ => {
                writeln!(
                    out,
                    "  Horizons queries NASA live for all supported bodies."
                )
                .ok();
                writeln!(out, "  SPK kernels are only useful as an offline fallback.").ok();
            }
        }
        let auto_spk = ask!(ask_yes_no(input, out, "auto_spk", auto_spk_default));
        if auto_spk {
            writeln!(
                out,
                "  Require an ephemeris-grade source for mapped minor bodies?"
            )
            .ok();
            writeln!(
                out,
                "  If disabled, a declared Keplerian approximation may be used."
            )
            .ok();
        } else {
            writeln!(
                out,
                "  Without auto-download, strict precision raises an error"
            )
            .ok();
            writeln!(
                out,
                "  for mapped minor bodies unless local SPK kernels are provisioned."
            )
            .ok();
        }
        let strict_precision = ask!(ask_yes_no(input, out, "strict_precision", auto_spk));

        writeln!(out, "\nTime precision").ok();
        writeln!(
            out,
            "  All modes convert UTC to astronomical time (TT) using Delta T."
        )
        .ok();
        writeln!(
            out,
            "  Built-in tables are accurate through ~2020. Download latest"
        )
        .ok();
        writeln!(
            out,
            "  IERS data (~3 MB) for best precision on recent/future dates?"
        )
        .ok();
        if mode == "horizons" {
            writeln!(
                out,
                "  Recommended in horizons mode since you're already online."
            )
            .ok();
        }
        let iers = ask!(ask_yes_no(
            input,
            out,
            "download IERS data",
            mode == "horizons"
        ));
        if !iers {
            writeln!(out, "  (iers_delta_t skipped - requires IERS data)").ok();
        }

        writeln!(out, "\nData directory").ok();
        writeln!(
            out,
            "  Base folder for all downloads (DE kernels, LEB, SPK, IERS)."
        )
        .ok();
        let data_dir = ask!(ask_text(input, out, "data directory", "~/.libephemeris"));
        let data_dir = data_dir.trim().to_string();
        let effective_data_dir = if data_dir.is_empty() {
            "~/.libephemeris".to_string()
        } else {
            data_dir.clone()
        };

        writeln!(
            out,
            "  Sub-paths are derived automatically from the data directory."
        )
        .ok();
        let customize = ask!(ask_yes_no(input, out, "Customize sub-paths?", false));

        let mut config = WizardConfig {
            precision: tier.clone(),
            mode: mode.clone(),
            network_policy: if mode == "leb" {
                "sealed".to_string()
            } else {
                "auto".to_string()
            },
            auto_spk,
            strict_precision,
            iers_auto_download: iers,
            iers_delta_t: iers,
            data_dir: if effective_data_dir == "~/.libephemeris" {
                None
            } else {
                Some(effective_data_dir.clone())
            },
            leb_file: None,
            spk_dir: None,
            ephemeris: None,
        };

        if customize {
            let expanded = expand_tilde(&effective_data_dir);
            if mode == "auto" || mode == "leb" {
                writeln!(
                    out,
                    "  Directory containing .leb/.leb2 binary ephemeris files."
                )
                .ok();
                let default_leb = expanded.join("leb").to_string_lossy().to_string();
                let leb = ask!(ask_text(input, out, "leb_file", &default_leb));
                if !leb.trim().is_empty() {
                    config.leb_file = Some(resolve_leb_entry(leb.trim(), &tier));
                }
            }
            writeln!(
                out,
                "  Cache directory for downloaded minor body SPK kernels."
            )
            .ok();
            let default_spk = expanded.join("spk").to_string_lossy().to_string();
            let spk = ask!(ask_text(input, out, "spk_dir", &default_spk));
            if !spk.trim().is_empty() {
                config.spk_dir = Some(spk.trim().to_string());
            }
            if mode == "auto" || mode == "skyfield" {
                writeln!(out, "  DE kernel filename override (leave empty for auto).").ok();
                let eph = ask!(ask_text(input, out, "ephemeris", ""));
                if !eph.trim().is_empty() {
                    config.ephemeris = Some(eph.trim().to_string());
                }
            }
            if mode == "skyfield" {
                writeln!(
                    out,
                    "  Path to .leb/.leb2 file (not needed in skyfield mode"
                )
                .ok();
                writeln!(
                    out,
                    "  unless you plan to switch to auto or leb mode later)."
                )
                .ok();
                let leb = ask!(ask_text(input, out, "leb_file", ""));
                if !leb.trim().is_empty() {
                    config.leb_file = Some(resolve_leb_entry(leb.trim(), &tier));
                }
            }
            if mode == "horizons" {
                writeln!(out, "  DE kernel and LEB are not needed in horizons mode").ok();
                writeln!(out, "  unless you plan to switch modes later.").ok();
            }
        }
        writeln!(out).ok();
        (config, effective_data_dir)
    };

    // The all-defaults answer keeps the exact `--non-interactive` bytes;
    // customized answers use the release generator layout.
    let text = if config == WizardConfig::defaults() {
        default_config_toml()
    } else {
        render_config_toml(&config)
    };
    if let Err(error) = std::fs::write(output, text) {
        writeln!(err, "libephemeris init: cannot write '{output}': {error}").ok();
        return EXIT_FAILED;
    }
    writeln!(out, "  Created {output}").ok();
    run_wizard_post(out, &config, &data_dir, output);
    EXIT_OK
}

/// Run `init --non-interactive`: write the defaults file.
pub(super) fn run_init(output: &str, force: bool) -> i32 {
    match write_config_file(output, force) {
        Ok(path) => {
            println!("wrote {path}");
            EXIT_OK
        }
        Err(message) => {
            eprintln!("libephemeris init: {message}");
            EXIT_FAILED
        }
    }
}

/// Run bare `init`: the interactive wizard over the real stdio streams.
pub(super) fn run_init_wizard(output: &str, force: bool) -> i32 {
    let stdin = std::io::stdin();
    let mut input = stdin.lock();
    let mut out = std::io::stdout().lock();
    let mut err = std::io::stderr().lock();
    run_wizard_io(&mut input, &mut out, &mut err, output, force)
}

