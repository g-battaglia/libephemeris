    fn wizard_io(stdin: &str, output: &std::path::Path, force: bool) -> (i32, String, String) {
        let mut input = std::io::BufReader::new(std::io::Cursor::new(stdin.to_string()));
        let mut out = Vec::new();
        let mut err = Vec::new();
        let code = run_wizard_io(
            &mut input,
            &mut out,
            &mut err,
            &output.to_string_lossy(),
            force,
        );
        (
            code,
            String::from_utf8_lossy(&out).to_string(),
            String::from_utf8_lossy(&err).to_string(),
        )
    }

    #[test]
    fn wizard_prompts_take_defaults_and_reject_garbage() {
        let mut out = Vec::new();
        // Empty takes the default; y/n spellings are case-insensitive.
        for (answer, default, expected) in [
            ("", true, true),
            ("", false, false),
            ("y", false, true),
            ("NO", true, false),
        ] {
            let mut input =
                std::io::BufReader::new(std::io::Cursor::new(answer.to_string() + "\n"));
            assert_eq!(
                ask_yes_no(&mut input, &mut out, "q?", default),
                Some(expected)
            );
        }
        // Garbage is re-asked, then accepted once valid.
        let mut input = std::io::BufReader::new(std::io::Cursor::new("maybe\nn\n".to_string()));
        assert_eq!(ask_yes_no(&mut input, &mut out, "q?", true), Some(false));
        // Five invalid answers give up; EOF gives up immediately.
        let mut input =
            std::io::BufReader::new(std::io::Cursor::new("x\nx\nx\nx\nx\n".to_string()));
        assert_eq!(ask_yes_no(&mut input, &mut out, "q?", true), None);
        let mut input = std::io::BufReader::new(std::io::Cursor::new(String::new()));
        assert_eq!(ask_yes_no(&mut input, &mut out, "q?", true), None);
        // Choices take numbers, values, or the default; EOF gives up.
        let options = [("auto", "first"), ("leb", "second")];
        let mut input = std::io::BufReader::new(std::io::Cursor::new("2\n".to_string()));
        assert_eq!(
            ask_choice(&mut input, &mut out, &options, 0),
            Some("leb".to_string())
        );
        let mut input = std::io::BufReader::new(std::io::Cursor::new("LEB\n".to_string()));
        assert_eq!(
            ask_choice(&mut input, &mut out, &options, 0),
            Some("leb".to_string())
        );
        let mut input = std::io::BufReader::new(std::io::Cursor::new("\n".to_string()));
        assert_eq!(
            ask_choice(&mut input, &mut out, &options, 1),
            Some("leb".to_string())
        );
        let mut input = std::io::BufReader::new(std::io::Cursor::new(String::new()));
        assert_eq!(ask_choice(&mut input, &mut out, &options, 0), None);
    }

