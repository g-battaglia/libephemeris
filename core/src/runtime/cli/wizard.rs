/// Parse `init` options without performing I/O.
///
/// Accept `-o`/`--output`, `-f`/`--force` and `--non-interactive`.
/// Unknown flags and a missing output path return a usage error. Without
/// `--non-interactive`, the command runs the numbered setup prompts.
pub(super) fn parse_init_args<'a>(
    args: &mut std::iter::Peekable<impl Iterator<Item = &'a str>>,
) -> Result<Command, String> {
    let mut output = "libephemeris-config.toml".to_string();
    let mut force = false;
    let mut non_interactive = false;
    while let Some(arg) = args.next() {
        if arg == "--force" || arg == "-f" {
            force = true;
        } else if arg == "--non-interactive" {
            non_interactive = true;
        } else if arg == "--output" || arg == "-o" {
            match args.next() {
                Some(path) => output = path.to_string(),
                None => return Err("--output needs a value".to_string()),
            }
        } else {
            return Err(format!("unexpected argument '{arg}'"));
        }
    }
    Ok(Command::Init {
        output,
        force,
        non_interactive,
    })
}

