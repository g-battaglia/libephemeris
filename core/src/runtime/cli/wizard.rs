/// Write the defaults file, refusing to overwrite without `force`.
///
/// Return the output path on success or a diagnostic on refusal or I/O failure.
/// Missing parent directories are not created.
fn write_config_file(output: &str, force: bool) -> Result<String, String> {
    let path = Path::new(output);
    if path.exists() && !force {
        return Err(format!(
            "refusing to overwrite existing '{output}'; rerun with --force"
        ));
    }
    std::fs::write(path, default_config_toml())
        .map_err(|error| format!("cannot write '{output}': {error}"))?;
    Ok(output.to_string())
}

/// Configuration answers collected by [`run_wizard_io`].
